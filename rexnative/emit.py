"""Writes a game layer: game_layer.h, d3d_surface.inc and layer.json.

A layer is the normalised dict both the adapter's result and a hand-made port's profile turn
into (`from_result`, `from_profile`), so the two can be written the same way and diffed.
"""
import json
import os

from . import profile as prof

HOOK_ORDER = ['BeginVertices', 'DrawVerticesUP', 'BeginIndexedVertices', 'DrawIndexedVerticesUP',
              'DrawVertices', 'DrawIndexedVertices',
              'DrawIndx2Inline', 'DrawIndx2Split', 'ClearF', 'Clear', 'Resolve', 'Swap',
              'RunCommandBuffer', 'QueryIssue', 'QueryGetData']


def from_result(res):
    t = res['target']
    info = t.get('xex') or {}
    funcs = {}
    for canon in prof.FUNCTIONS:
        r = res['functions'].get(canon, {})
        note = ''
        if r.get('address'):
            note = '%s, %s' % (r.get('how'), r.get('confidence'))
            if r.get('ref') and r['ref'] != res['primary']:
                note += ', from %s' % r['ref']
        elif r.get('detail'):
            note = 'not found; ' + r['detail']
        else:
            note = 'not found'
        funcs[canon] = (r.get('address'), note)
    surface = [(a, n, c, '%s %s%s' % (how, conf, (' ' + src) if src else ''))
               for a, n, c, how, conf, src in res['surface']]
    offs = {k: (v['target'], v['how']) for k, v in res['offsets'].items()}
    ra = res.get('resolve_abi') or {}
    return {
        'name': t['name'], 'title': t['title'],
        'title_id': info.get('title_id'), 'version': info.get('version'),
        'd3d': ' '.join(x for x in t.get('d3d', []) if x),
        'reference': res['primary'],
        'functions': funcs,
        'surface': surface,
        'offsets': offs,
        'clear_color': res.get('clear_color'),
        'resolve_args': ra.get('args', list(range(3, 11))),
        'resolve_stencil_reg': ra.get('stencil_reg', 0),
        'call_args': {k: v['args'] for k, v in (res.get('call_args') or {}).items()},
        'scene': res['scene'], 'defaults': res['defaults'], 'devices': res['devices'],
        'xinput_state_reg': res['functions'].get('XInputGetState', {}).get('state_reg', 4),
    }


def from_profile(p):
    info = p.get('xex') or {}
    from .xex import d3d_library
    lib, ver = d3d_library(info) if info else (None, None)
    funcs = {c: (p['functions'].get(c), 'hand-made' if p['functions'].get(c) else 'not found')
             for c in prof.FUNCTIONS}
    return {
        'name': p['name'], 'title': p['title'],
        'title_id': info.get('title_id'), 'version': info.get('version'),
        'd3d': ' '.join(x for x in (lib, ver) if x),
        'reference': 'hand-made',
        'functions': funcs,
        'surface': [(a, n, c, 'hand-made') for a, n, c in p['surface']],
        'offsets': {k: (v, 'hand-made') for k, v in p['offsets'].items()},
        'clear_color': p.get('clear_color'),
        'resolve_args': p['resolve_abi']['args'],
        'call_args': p.get('call_args') or {},
        'scene': p['scene'], 'defaults': p['defaults'], 'devices': p['devices'],
    }


def _hex(a):
    return '0x%08X' % a if a else '0'


def game_layer_h(layer, comments=True):
    c = (lambda s: ('  // ' + s) if comments and s else '')
    out = []
    w = out.append
    if comments:
        w('// Game layer of the native D3D12 renderer for %s.' % layer['title'])
        w('// Generated by ReXNative (python -m rexnative); edit overrides.json and')
        w('// generate again instead of editing this file.')
        w('// Title %s, version %s, %s; reference: %s.' % (layer['title_id'], layer['version'],
                                                          layer['d3d'], layer['reference']))
    w('#pragma once')
    w('')
    w('#include <cstdint>')
    w('')
    w('namespace rexnative::game {')
    w('')
    w('inline constexpr char kGameName[] = "%s";' % layer['title'].replace('"', "'"))
    w('inline constexpr uint32_t kTitleId = 0x%s;' % (layer['title_id'] or '00000000'))
    w('')
    if comments:
        w('// Guest D3D functions (0 = not found in this game).')
    for canon in prof.FUNCTIONS:
        a, note = layer['functions'][canon]
        w('inline constexpr uint32_t kFn%s = %s;%s' % (canon, _hex(a), c(note)))
    w('')
    if comments:
        w('// HookFn values (hook_args.h): the address, or a distinct value below 0x100 when the')
        w('// function was not found (no hook has it).')
    sentinel = 1
    for canon in HOOK_ORDER:
        a = layer['functions'][canon][0]
        if not a:
            a, sentinel = sentinel, sentinel + 1
        w('inline constexpr uint32_t kHook%s = 0x%08X;' % (canon, a))
    w('')
    if comments:
        w('// Hooked by symbol (REX_HOOK_RAW / REX_EXTERN take sub_XXXXXXXX tokens).')
    for canon, macro in (('ShaderLoad', 'REXNATIVE_SHADER_LOAD'), ('ImmediateVs', 'REXNATIVE_IMMEDIATE_VS'),
                         ('XInputGetState', 'REXNATIVE_XINPUT_GET_STATE')):
        a = layer['functions'][canon][0]
        w('#define %s %s' % (macro, ('%08X' % a) if a else '00000000'))
        w('#define %s_FOUND %d' % (macro, 1 if a else 0))
    if comments:
        w("// Where XInputGetState's hook finds the state: r4 (user, state), or r5 when it is the")
        w('// XamInputGetState thunk (user, flags, state).')
    w('#define REXNATIVE_XINPUT_STATE_REG %d' % int(layer.get('xinput_state_reg', 4)))
    w('#define REXNATIVE_SUB_(a) sub_##a')
    w('#define REXNATIVE_SUB(a) REXNATIVE_SUB_(a)')
    w('#define REXNATIVE_IMP_(a) __imp__sub_##a')
    w('#define REXNATIVE_IMP(a) REXNATIVE_IMP_(a)')
    w('')
    groups = {}
    for k, (v, note) in layer['offsets'].items():
        ns, _, name = k.partition('.')
        groups.setdefault(ns, []).append((name, v, note))
    if comments:
        w('// Guest D3D device field offsets.')
    for ns in ('dev', 'shadow', 'rt', 'occ'):
        if ns not in groups:
            continue
        w('namespace %s {' % ns)
        for name, v, note in groups[ns]:
            ident = name if ns != 'shadow' else 'k' + name
            w('inline constexpr uint32_t %s = %d;%s' % (ident, v, c(note)))
        w('}  // namespace %s' % ns)
    w('')
    cc = layer.get('clear_color') or {'address': 0, 'vector': False}
    if comments:
        w('// Resolve: the default clear colour (pClearColor NULL) and where each public argument')
        w('// (r3 device .. r10 clear_color, hook_args.h) is at the hooked function\'s entry: the')
        w('// entry register, 0 for a constant 0.')
    w('inline constexpr uint32_t kResolveDefaultClearColor = %s;' % _hex(cc['address']))
    w('inline constexpr bool kResolveDefaultClearIsVector = %s;' % ('true' if cc['vector'] else 'false'))
    args = layer['resolve_args']
    w('inline constexpr uint8_t kResolveArgRegs[8] = {%s};' % ', '.join(str(x or 0) for x in args))
    if comments:
        w('// The same for the hooked draw functions (LTCG builds drop and move their arguments).')
    from .abi import CALL_ARG_FUNCTIONS
    for canon in CALL_ARG_FUNCTIONS:
        regs = (layer.get('call_args') or {}).get(canon) or list(range(3, 11))
        w('inline constexpr uint8_t kArgs%s[8] = {%s};' % (canon, ', '.join(str(x or 0) for x in regs)))
        w('inline constexpr bool kRemap%s = %s;' % (
            canon, 'false' if list(regs) == list(range(3, 11)) else 'true'))
    w('inline constexpr bool kResolveRemapArgs = %s;' % (
        'false' if list(args) == list(range(3, 11)) else 'true'))
    stencil = layer.get('resolve_stencil_reg') or 0
    if stencil:
        if comments:
            w('// Resolve\'s ClearStencil in this register at entry (0 or absent: on the stack).')
        w('#define REXNATIVE_RESOLVE_STENCIL_REG %d' % stencil)
    w('')
    dv = layer['devices']
    if comments:
        w('// Devices: follow only the device the game presents with (Iron Brigade drives a second')
        w('// one while loading); configure the tap at the first device seen when CreateDevice is')
        w('// not hooked.')
    w('inline constexpr bool kFollowSwapDeviceOnly = %s;' % str(bool(dv.get('follow_swap_device_only'))).lower())
    w('inline constexpr bool kConfigureAtFirstDevice = %s;' % str(bool(dv.get('configure_at_first_device'))).lower())
    w('')
    sc = layer['scene']
    if comments:
        w('// The scene surface the upscaler (DLSS / DLAA), the MSAA option and DLSS 5 work on: not in')
        w('// the code. REXNATIVE_SCENE_AUTO 1: the renderer learns it from the frames\' resolves')
        w('// (scene.h); 0: these constants, measured (python -m rexnative scene <resolve dump>).')
        w('// --rexnative_scene_auto=0/1 overrides it at run time.')
    w('inline constexpr uint32_t kSceneSurfaceMask = 0x%X;' % sc.get('kSceneSurfaceMask', 0x33FFF))
    w('inline constexpr uint32_t kSceneSurface = 0x%X;' % sc.get('kSceneSurface', 0))
    w('inline constexpr uint32_t kSceneWidth = %d;' % sc.get('width', 0))
    w('inline constexpr uint32_t kScenePitch = %d;' % sc.get('scaled_pitch', sc.get('width', 0)))
    w('inline constexpr uint32_t kGameFrameHeight = %d;' % sc.get('height', 0))
    w('#define REXNATIVE_SCENE_AUTO %d' % (1 if sc.get('auto') else 0))
    w('')
    d = layer['defaults']
    if comments:
        w('// Defaults of the game\'s options (rexnative, rexnative_render_height,')
        w('// rexnative_occlusion, rexnative_display_aspect, rexnative_cmdbuf).')
    if comments:
        w('// kDefaultEnabled: ReXNative draws and presents the game unless --rexnative=false.')
    w('inline constexpr bool kDefaultEnabled = %s;' % str(bool(d.get('enabled', True))).lower())
    w('inline constexpr int32_t kDefaultRenderHeight = %d;' % d.get('render_height', sc.get('height', 720)))
    w('inline constexpr bool kDefaultOcclusion = %s;' % str(bool(d.get('occlusion', False))).lower())
    w('inline constexpr double kDefaultDisplayAspect = %s;' % d.get('display_aspect', '16.0 / 9.0'))
    if comments:
        w('// kDefaultCmdBuf: recorded command buffers (RunCommandBuffer): 0 off, 1 count, 2 replay.')
    w('inline constexpr int32_t kDefaultCmdBuf = %d;' % int(d.get('cmdbuf', 0)))
    if d.get('cmdbuf_bin_mask'):
        if comments:
            w("// kCmdBufBinMaskOffset: the device's bin mask, which a replayed buffer starts from.")
        w('inline constexpr uint32_t kCmdBufBinMaskOffset = %d;' % int(d['cmdbuf_bin_mask']))
    w('')
    w('}  // namespace rexnative::game')
    return '\n'.join(out) + '\n'


def surface_inc(layer, comments=True):
    out = []
    if comments:
        out.append('// Guest D3D entry points hooked for %s (d3d_surface.inc).' % layer['title'])
        out.append('// Generated by ReXNative from %s\'s: names stay the reference\'s.'
                   % layer['reference'])
        out.append('// D3D_FN(address, name, category)  // how matched, confidence')
    for a, n, cat, note in sorted(layer['surface']):
        out.append('D3D_FN(%08X, "%s", %s)%s' % (a, n, cat, ('  // ' + note) if comments else ''))
    return '\n'.join(out) + '\n'


def write(layer, out_dir, result=None):
    os.makedirs(out_dir, exist_ok=True)
    files = {
        'game_layer.h': game_layer_h(layer),
        'd3d_surface.inc': surface_inc(layer),
    }
    for name, text in files.items():
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    if result is not None:
        with open(os.path.join(out_dir, 'layer.json'), 'w', encoding='utf-8', newline='\n') as f:
            json.dump(jsonable(result), f, indent=1)
            f.write('\n')
    return list(files)


def jsonable(obj):
    if isinstance(obj, dict):
        return {str(k): jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [jsonable(v) for v in obj]
    if isinstance(obj, int) and not isinstance(obj, bool) and obj >= 0x80000000:
        return '%08X' % obj
    return obj
